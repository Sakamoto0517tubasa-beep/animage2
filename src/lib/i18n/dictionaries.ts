export const DICTIONARIES: Record<Locale, Dict> = { ja, en, "zh-CN": zhCN, ko, es };

export function translate(locale: Locale, key: string): string {
  return DICTIONARIES[locale]?.[key] ?? DICTIONARIES.ja[key] ?? key;
}

// {n} などのプレースホルダを置換するヘルパ
export function translateWith(locale: Locale, key: string, params: Record<string, string | number>): string {
  let s = translate(locale, key);
  for (const [k, v] of Object.entries(params)) {
    s = s.replace(`{${k}}`, String(v));
  }
  return s;
}
